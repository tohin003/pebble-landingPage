// post-credit review's P2-9: no riverbed pebble on the night plate may read larger than the sleeping stone). The plate is
// the site's own night wallpaper, tools/assets/wallpaper/wallpaper-dark.svg (capture/riverbed-plate.mjs renders it,
// without its vignette, into video/public/desktop/riverbed-dark@3x.png, and coda.ts CODA_PLATE draws its 2400-px JPEG):
// a 1600 × 1000 viewBox whose nine pebbles are each one clip path, c0–c8 (one M, 64 cubic segments, Z), drawn as their
// own fill. CODA_PLATE_PEBBLES is GENERATED from that file by platePebbles(): every other on-curve point of each outline,
// in the plate's units (a chord there strays under 2 units from the curve). tests/coda.test.ts parses the file again and
// fails when it no longer matches, printing the new constant (platePebblesSource) to paste here.
// Pure.

/** The plate's own units: its viewBox (the plate is 1.6:1, as the riverbed is: setpieces/ground.ts RIVERBED.aspect). */
export const PLATE_UNITS = { w: 1600, h: 1000 } as const;

/** The wallpaper the plate is rendered from, repo-relative (the test reads it). */
export const PLATE_SOURCE = "tools/assets/wallpaper/wallpaper-dark.svg";

/** One riverbed pebble of the plate: its clip path's id and its outline (plate units, a closed polygon). */
export interface PlatePebble {
  id: string;
  outline: readonly (readonly [number, number])[];
}

/**
 * The plate's pebbles from the wallpaper's SVG text: each `<clipPath id="cN"><path d="M x y C … Z"/>`, its on-curve
 * points (every `every`-th segment's end, from the M), rounded to whole units. Throws on a path it cannot read.
 */
export function platePebbles(svg: string, every = 2): PlatePebble[] {
  const out: PlatePebble[] = [];
  for (const m of svg.matchAll(/<clipPath id="(c\d+)"><path d="([^"]+)"/g)) {
    const toks = [...m[2]!.matchAll(/[A-Za-z]|-?\d+(?:\.\d+)?/g)].map((t) => t[0]);
    const pts: [number, number][] = [];
    let i = 0;
    let seg = 0;
    const num = () => {
      const v = Number(toks[i++]);
      if (!Number.isFinite(v)) throw new Error(`${m[1]}: a number expected at token ${i - 1}`);
      return v;
    };
    while (i < toks.length) {
      const c = toks[i++]!;
      if (c === "M") pts.push([Math.round(num()), Math.round(num())]);
      else if (c === "C") {
        i += 4; // the two control points
        const x = num();
        const y = num();
        seg++;
        if (seg % every === 0) pts.push([Math.round(x), Math.round(y)]);
      } else if (c === "Z" || c === "z") break;
      else throw new Error(`${m[1]}: the plate's pebbles are M, C and Z paths (found ${c})`);
    }
    // the last segment ends on the start: drop the repeat
    const [a, b] = [pts[0]!, pts[pts.length - 1]!];
    if (pts.length > 1 && a[0] === b[0] && a[1] === b[1]) pts.pop();
    if (pts.length < 8) throw new Error(`${m[1]}: too few points (${pts.length})`);
    out.push({ id: m[1]!, outline: pts });
  }
  return out;
}

