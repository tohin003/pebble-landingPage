#!/usr/bin/env python3
"""The score's energy, one value a video frame, for the pebble's aura and the motion's intensity.

  python3 -I video/src/reel/energy.py <score.wav> <out.ts> <EXPORT_NAME> [--fps 60]

FFmpeg ($FF, else /opt/homebrew/bin/ffmpeg) decodes the mix to mono float at 6 kHz; each frame's RMS (dB) is taken over
its own 1/fps window. `level` is that loudness mapped to 0..1 between the mix's quiet floor (10th percentile) and its
peak (99th), smoothed with a fast attack and a slower release, so light follows the music without flicker. Writes a
TypeScript module (numbers only; the audio itself is never in git).
"""
import math
import os
import subprocess
import sys
from array import array


def main() -> None:
    a = sys.argv[1:]
    if len(a) < 3:
        print(__doc__)
        sys.exit(64)
    wav, out, name = a[0], a[1], a[2]
    fps = int(a[a.index("--fps") + 1]) if "--fps" in a else 60
    sr = 6000
    ff = os.environ.get("FF", "/opt/homebrew/bin/ffmpeg")
    raw = subprocess.run([ff, "-hide_banner", "-loglevel", "error", "-i", wav, "-ac", "1", "-ar", str(sr), "-f", "f32le", "-"], check=True, capture_output=True).stdout
    x = array("f")
    x.frombytes(raw)
    hop = sr / fps
    n = int(len(x) / hop)
    db = []
    for i in range(n):
        s = x[int(i * hop): int((i + 1) * hop)]
        ms = sum(v * v for v in s) / max(1, len(s))
        db.append(10 * math.log10(ms + 1e-12))
    srt = sorted(d for d in db if d > -90)
    floor = srt[int(len(srt) * 0.10)] if srt else -60
    peak = srt[int(len(srt) * 0.99)] if srt else 0
    lin = [min(1.0, max(0.0, (d - floor) / max(1e-6, peak - floor))) for d in db]
    lvl, v = [], lin[0] if lin else 0.0
    for u in lin:
        k = 0.55 if u > v else 0.08  # attack about 2 frames, release about 12
        v += (u - v) * k
        lvl.append(v)
    with open(out, "w") as f:
        f.write(
            f"// Generated by video/src/reel/energy.py from {os.path.basename(wav)} (the music lane's mix): per-frame RMS in dB at\n"
            f"// {fps} fps and `level`, the loudness mapped to 0..1 between the mix's floor ({floor:.1f} dB) and peak ({peak:.1f} dB), smoothed.\n"
            f"export const {name} = {{\n  fps: {fps},\n  floorDb: {floor:.2f},\n  peakDb: {peak:.2f},\n"
            f"  db: [{', '.join(f'{d:.1f}' for d in db)}],\n"
            f"  level: [{', '.join(f'{l:.3f}' for l in lvl)}],\n}} as const;\n"
        )
    print(f"{out}: {n} frames, floor {floor:.1f} dB, peak {peak:.1f} dB")


if __name__ == "__main__":
    main()
